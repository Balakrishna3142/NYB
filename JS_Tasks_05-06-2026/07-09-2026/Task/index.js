// Variables and different data types
let name = "Ravi";       // String
let age = 20;             // Number
let isStudent = true;     // Boolean
let marks = 85.5;         // Number

// Operators
let nextYearAge = age + 1;
let totalMarks = marks + 10;
let passed = marks >= 35;

// Template literal
console.log(`Name: ${name}`);
console.log(`Age: ${age}`);
console.log(`Age next year: ${nextYearAge}`);
console.log(`Marks: ${marks}`);
console.log(`Total marks after bonus: ${totalMarks}`);
console.log(`Student: ${isStudent}`);
console.log(`Passed: ${passed}`);