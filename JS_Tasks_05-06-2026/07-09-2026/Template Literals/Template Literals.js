

let name = "Balakrisha";
let age = 20;
let course = "JavaScript";

// 1. String interpolation
let message = `My name is ${name}.`;
console.log(message);

// 2. Using expressions
console.log(`I will be ${age + 1} years old next year.`);

// 3. Multiple variables
console.log(`I am ${age} years old and I am learning ${course}.`);

// 4. Multi-line string
let details = `
Name: ${name}
Age: ${age}
Course: ${course}
`;

console.log(details);