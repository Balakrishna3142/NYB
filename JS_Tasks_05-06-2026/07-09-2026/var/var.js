

// Example of var
var name = "Giri";
console.log("Name using var:", name);

// Example of let
let age = 20;
console.log("Age using let:", age);

// Example of const
const country = "India";
console.log("Country using const:", country);

// Changing a var variable
var name = "Krishna";
console.log("Changed name:", name);

// Changing a let variable
age = 21;
console.log("Changed age:", age);

// const cannot be changed
console.log("Constant country:", country);